const ACCOUNT_RTL = new Set(["fa","ar","ckb"]);

function localizeAccountHtml(html, language = "en") {
  const lang = ACCOUNT_COPY[language] ? language : "en";
  const copy = ACCOUNT_COPY[lang];

  html = html.replace('<html lang="en">', `<html lang="${lang}" dir="${ACCOUNT_RTL.has(lang) ? "rtl" : "ltr"}">`);

  for (const [source, target] of Object.entries(copy)) {
    if (source !== target) html = html.split(source).join(target);
  }

  return html;
}
export function accountSiteShell(pathname = "/account", language = "en") {
  let html = null;
  if (pathname === "/account") html = overview();
  else if (pathname === "/account/profile") html = liveProfile();
  else if (pathname === "/account/rfqs") html = detail("RFQs", "RFQs", "Review business requests and their supplier-matching lifecycle.", ["Submitted RFQs", "Supplier match status", "Request details and timing"]);
  else if (pathname === "/account/quotes") html = detail("Quotes", "Quotes", "Review supplier quotations associated with accepted or pending RFQs.", ["Quote status", "Supplier reference", "Commercial terms and expiry"]);
  else if (pathname === "/account/orders") return null;
  else if (pathname === "/account/documents") html = detail("Documents", "Documents", "A dedicated place for commercial and order-related documents.", ["RFQ documents", "Quotation documents", "Order documents"]);
  else if (pathname === "/account/settings") html = settings();
  else return null;

  return localizeAccountHtml(html, language);
}

export function accountSiteResponse(pathname = "/account", language = "en") {
  const html = accountSiteShell(pathname, language);
  if (!html) return new Response("Not Found", { status: 404, headers: { "content-type": "text/plain; charset=utf-8" } });
  return new Response(html, { status: 200, headers: { "content-type": "text/html; charset=utf-8", "cache-control": "no-store" } });
}
